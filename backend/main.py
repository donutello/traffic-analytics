@app.get("/api/health")
def health() -> dict[str, str]:
    return {"status": "ok"}


@app.get("/api/meta", response_model=MetaOut)
def get_meta(db: Db) -> dict:
    roads = [
        {"code": road, "name": road_name, "sensors": count}
        for road, road_name, count in db.execute(
            "SELECT road, road_name, COUNT(*) FROM sensors GROUP BY road, road_name ORDER BY road"
        ).fetchall()
    ]
    period = db.execute("SELECT date(MIN(ts)), date(MAX(ts)) FROM measurements").fetchone()
    return {"roads": roads, "period": {"from": period[0], "to": period[1]}}


@app.get("/api/series", response_model=SeriesOut)
def get_series(
    db: Db,
    sensor: str,
    granularity: Granularity = "hour",
    start: FromParam = None,
    end: ToParam = None,
) -> dict:
    """One sensor's series; day and week groups average the hours of the group (gen_mock)."""
    bounds, args = [], [sensor]
    lo, hi = parse_bound(start, end=False), parse_bound(end, end=True)
    if lo:
        bounds.append("m.ts >= ?")
        args.append(lo)
    if hi:
        bounds.append("m.ts < ?")
        args.append(hi)
    where = " AND ".join(["m.sensor_id = ?", *bounds])

    if granularity == "hour":
        rows = db.execute(
            f"SELECT m.ts, m.volume, CASE WHEN {COVERED_HOUR} THEN 'anomaly' ELSE m.state END"
            f" AS state FROM measurements m WHERE {where} ORDER BY m.ts",
            args,
        ).fetchall()
        points = [
            {"ts": with_offset(ts), "label": ts[11:16], "volume": volume, "state": state}
            for ts, volume, state in rows
        ]
        return {"points": points}

    # day buckets are Moscow calendar days; a week bucket starts on its Moscow Monday
    bucket = "date(m.ts)" if granularity == "day" else "date(m.ts, 'weekday 0', '-6 days')"
    rows = db.execute(
        f"SELECT {bucket} AS bucket, SUM(m.volume), COUNT(*), MAX({COVERED_HOUR}),"
        f" MAX(m.state = 'imputed') FROM measurements m WHERE {where}"
        " GROUP BY bucket ORDER BY bucket",
        args,
    ).fetchall()
    points = []
    for day, total, hours, any_anomaly, any_imputed in rows:
        state = "anomaly" if any_anomaly else "imputed" if any_imputed else "normal"
        points.append(
            {
                "ts": day,
                "label": day_label(date.fromisoformat(day)),
                "volume": round(total / hours),
                "state": state,
            }
        )
    return {"points": points}


@app.get("/api/sensors", response_model=SensorsOut)
def get_sensors(
    db: Db,
    road: str | None = None,
    start: FromParam = None,
    end: ToParam = None,
) -> dict:
    """The map: every sensor with its anomaly count in the period and mega flag."""
    parts = period_conditions(parse_bound(start, False), parse_bound(end, True), "a")
    period = "".join(f" AND {sql}" for sql, _ in parts)
    args = [value for _, value in parts]
    counts: dict[str, int] = {}
    for sensor_id, _source, count in db.execute(
        "SELECT a.sensor_id, a.source, COUNT(*) FROM anomalies a"
        f" WHERE 1{period} GROUP BY a.sensor_id, a.source",
        args,
    ).fetchall():
        counts[sensor_id] = counts.get(sensor_id, 0) + count
    mega = {
        row[0]
        for row in db.execute(
            "SELECT sensor_id FROM anomalies WHERE is_mega = 1"  # of any period, per contract.md
        ).fetchall()
    }

    where, sensor_args = ("WHERE road = ?", [road]) if road else ("", [])
    features = []
    for sensor_id, name, sensor_road, km, lon, lat, direct, reverse in db.execute(
        "SELECT id, name, road, km, lon, lat, direction_direct, direction_reverse"
        f" FROM sensors {where} ORDER BY road, km",
        sensor_args,
    ).fetchall():
        features.append(
            {
                "geometry": {"coordinates": [lon, lat]},
                "properties": {
                    "id": sensor_id,
                    "name": name,
                    "road": sensor_road,
                    "km": km,
                    "anomaly_count": counts.get(sensor_id, 0),
                    "is_mega": sensor_id in mega,
                    "directions": {"direct": direct, "reverse": reverse},
                },
            }
        )
    return {"features": features}


@app.get("/api/anomalies", response_model=AnomalyListOut)
def get_anomalies(
    db: Db,
    road: str | None = None,
    sensor: str | None = None,
    start: FromParam = None,
    end: ToParam = None,
    anomaly_type: Annotated[str | None, Query(alias="type")] = None,
    source: Source | None = None,
    level: Level | None = None,
) -> dict:
    """The side panel: our and the corporate system's findings, ours+corporate in one list."""
    conditions = []
    for value, column in (
        (road, "a.road"),
        (sensor, "a.sensor_id"),
        (anomaly_type, "a.type"),
        (source, "a.source"),
        (level, "a.level"),
    ):
        if value:
            conditions.append((f"{column} = ?", value))
    parts = period_conditions(parse_bound(start, False), parse_bound(end, True), "a")
    conditions += parts
    where = " WHERE " + " AND ".join(sql for sql, _ in conditions) if conditions else ""
    args = [value for _, value in conditions]

    rows = db.execute(ANOMALY_SELECT + where + " ORDER BY a.starts_at, a.id", args).fetchall()
    last_day = data_last_day(db)
    items = [anomaly_item(row, last_day) for row in rows]
    return {
        "counts": {
            "ours": sum(1 for item in items if item["source"] == "ours"),
            "corporate": sum(1 for item in items if item["source"] == "corporate"),
        },
        "anomalies": items,
    }


@app.get("/api/anomalies/{anomaly_id}", response_model=AnomalyDetail)
def get_anomaly(db: Db, anomaly_id: str) -> dict:
    """One finding with its sizes and, when an event explains it, the event and its link."""
    row = db.execute(ANOMALY_SELECT + " WHERE a.id = ?", (anomaly_id,)).fetchone()
    if row is None:
        raise HTTPException(404, f"anomaly {anomaly_id!r} is not in the database")
    item = anomaly_item(row, data_last_day(db))

    event = None
    if item["event_id"]:
        found = db.execute(
            "SELECT id, date, category, title, description, source_url FROM events WHERE id = ?",
            (item["event_id"],),
        ).fetchone()
        if found is not None:
            event_id, event_date, category, title, description, source_url = found
            event = {
                "id": event_id,
                "date": event_date,
                "date_label": day_label(date.fromisoformat(event_date)),
                "category": category,
                "category_label": EVENT_CATEGORY_LABELS[category],
                "title": title,
                "description": description,
                "source_url": source_url,
            }
    return {**item, "event": event}
