# sensor_name comes from sensors (docs/contract.md); the extra column is the last one.
ANOMALY_SELECT = (
    "SELECT a."
    + ", a.".join(ANOMALY_COLUMNS)
    + ", s.name FROM anomalies a JOIN sensors s ON s.id = a.sensor_id"
)

Db = Annotated[libsql.Connection, Depends(get_db)]
FromParam = Annotated[str | None, Query(alias="from", description="date or ISO 8601 time")]
ToParam = Annotated[str | None, Query(alias="to", description="date or ISO 8601 time")]


# ---------------------------------------------------------------- helpers


def with_offset(stored: str) -> str:
    """Naive Moscow text from the database ('2025-03-08 09:00:00') to contract time."""
    return f"{stored[:10]}T{stored[11:]}{MOSCOW}"


def parse_bound(value: str | None, end: bool) -> str | None:
    """A from/to parameter to naive Moscow text for comparing with the stored columns.

    A plain date means the whole Moscow day: as an end bound it becomes the next
    midnight, which every period filter here compares strictly (ts < to, starts_at < to).
    """
    if not value:
        return None
    try:
        moment = datetime.fromisoformat(value)
    except ValueError as exc:
        raise HTTPException(422, f"bad time {value!r}: write it as a date or ISO 8601") from exc
    if moment.tzinfo is None:  # a time without an offset is read as Moscow wall-clock time
        moment = moment.replace(tzinfo=MOSCOW_TZ)
    if end and len(value) == 10:
        moment += timedelta(days=1)
    return moment.astimezone(MOSCOW_TZ).strftime(TIME_FORMAT)


def day_label(day: date) -> str:
    return f"{day.day} {MONTHS[day.month - 1]}"


def time_label(moment: datetime) -> str:
    return f"{moment.day} {MONTHS[moment.month - 1]}, {moment:%H:%M}"


def parse_moment(stored: str) -> datetime:
    return datetime.strptime(stored, TIME_FORMAT)


def data_last_day(db: libsql.Connection) -> date | None:
    """The last day of the stored data: 'N дней назад' counts from it, as gen_mock does."""
    row = db.execute("SELECT date(MAX(ts)) FROM measurements").fetchone()
    return date.fromisoformat(row[0]) if row and row[0] else None


def period_conditions(lo: str | None, hi: str | None, alias: str) -> list[tuple[str, str]]:
    """Interval overlap of [starts_at, ends_at) with [lo, hi), as (sql, value) pairs."""
    parts = []
    if lo:
        parts.append((f"{alias}.ends_at > ?", lo))
    if hi:
        parts.append((f"{alias}.starts_at < ?", hi))
    return parts


def anomaly_item(row: tuple, last_day: date | None) -> dict:
    """One anomalies row (+ joined sensor_name as the last column) as an API item."""
    a = dict(zip(ANOMALY_COLUMNS, row, strict=False))  # the row ends with the sensor name
    starts, ends = parse_moment(a["starts_at"]), parse_moment(a["ends_at"])
    return {
        "id": a["id"],
        "sensor_id": a["sensor_id"],
        "sensor_name": row[-1],
        "starts_at": with_offset(a["starts_at"]),
        "ends_at": with_offset(a["ends_at"]),
        "starts_label": time_label(starts),
        "ends_label": time_label(ends),
        "duration_label": f"{round((ends - starts) / timedelta(hours=1))} ч",
        "days_ago": (last_day - starts.date()).days if last_day else 0,
        "category": a["category"],
        "category_label": CATEGORY_LABELS[a["category"]],
        "type": a["type"],
        "type_label": ANOMALY_TYPE_LABELS.get(a["type"], a["type"]),
        "detector": a["detector"],
        "level": a["level"],
        "level_label": LEVEL_LABELS[a["level"]],
        "metric": a["metric"],
        "actual": a["actual"],
        "expected": a["expected"],
        "deviation_pct": a["deviation_pct"],
        "score": a["score"],
        "is_mega": a["is_mega"],
        "event_id": a["event_id"],
        "description": a["description"],
        "source": a["source"],
        "source_label": SOURCE_LABELS[a["source"]],
    }


